-- Findings that inform a judgement but must never be quoted back.
--
-- Web research turns up solvency and debt-enforcement records: a poursuite
-- against a one-person Sàrl was the case that prompted this. Two reasons it
-- cannot live in `it_signals` beside "uses WordPress".
--
-- It is worth knowing. A company under enforcement is a different prospect
-- from one that is not, and deleting the finding would make the fit score
-- worse at the thing it exists to do.
--
-- It must not be repeated. For a single-manager Sàrl the company's finances
-- are an identifiable person's finances, which under the nLPD is not the same
-- category of fact as their opening hours, and the source is the open web
-- rather than the register. A drafted email that alludes to it would be
-- indefensible however true it is.
--
-- So it is stored in its own column, which the draft path never reads. A
-- separate column rather than a flag inside the JSON, because "never send
-- this" has to survive somebody writing a query in a hurry.
ALTER TABLE site ADD COLUMN restricted TEXT;
