-- Notes about a client, written in Markdown.
--
-- Three things already hold text about a client and none of them is this one.
-- `crm.dossier` is a fixed set of sections answering fixed questions, and its
-- shape is the point. `crm.interaction` is what happened on a date.
-- `crm.attachment` is a document the *client* sent, stored by content digest
-- and never edited. A note is none of those: it is the operator's own writing,
-- long-form, revised over weeks, and belonging to the engagement rather than
-- to any one day of it.
--
-- MARKDOWN AS THE STORED FORM, NOT AS A RENDERING STEP. The body is kept
-- exactly as typed, because that is what gets edited next, what an agent
-- should read, and what can be handed back out as a file. HTML is produced on
-- the way to a page and never stored: a stored rendering is a second copy that
-- drifts from the first.
--
-- WHY `source_path` IS A COLUMN. These are written in the editor the operator
-- already has, in a folder that already exists, and imported. Keying a
-- re-import on where the file came from is what makes the second import an
-- update rather than a duplicate, so editing the file and running the command
-- again does the obvious thing.

CREATE TABLE IF NOT EXISTS crm.note (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    -- Nullable, like an interaction's: a note can concern the relationship
    -- rather than any one piece of work.
    project_id  BIGINT REFERENCES crm.project (id) ON DELETE SET NULL,
    title       TEXT NOT NULL,
    body        TEXT NOT NULL,
    -- Only 'markdown' today. Named rather than assumed, so a note pasted as
    -- plain text later cannot be silently rendered as though it were markup.
    format      TEXT NOT NULL DEFAULT 'markdown',
    -- Where it was imported from, when it was. The path is the operator's own
    -- and is not shown to anyone else; it is here so a re-import updates the
    -- note it came from instead of writing a second one.
    source_path TEXT,
    -- The body's digest, so a re-import of an unchanged file can say so rather
    -- than bumping `updated_at` and claiming work that did not happen.
    sha256      TEXT NOT NULL,
    -- Free labels, for a note that is about access, or pricing, or the audit.
    tags        TEXT[] NOT NULL DEFAULT '{}',
    -- Kept at the top of the list. A standing brief among forty meeting notes
    -- is unfindable by date alone.
    pinned      BOOLEAN NOT NULL DEFAULT FALSE,
    author      TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (client_id, source_path)
);

CREATE INDEX IF NOT EXISTS note_client_idx
    ON crm.note (client_id, pinned DESC, updated_at DESC);
-- Notes are searched by what is in them, which is the only way a folder of
-- forty is usable. French, because they are written in it.
CREATE INDEX IF NOT EXISTS note_search_idx ON crm.note
    USING gin (to_tsvector('french', coalesce(title, '') || ' ' || coalesce(body, '')));
CREATE INDEX IF NOT EXISTS note_tags_idx ON crm.note USING gin (tags);
