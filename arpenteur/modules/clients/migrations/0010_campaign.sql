-- Curated lists, and campaigns sent from them in waves.
--
-- AN AUDIENCE IS NOT A CAMPAIGN. A list of firms worth writing to, each with
-- the one mailbox chosen for it, is built once and can serve several
-- campaigns; a campaign is one message plan over one list. Kept apart so a
-- second campaign to the same tourism offices does not repeat the curation,
-- and so a list can be argued with on its own.
--
-- EVERY FIRM IN SCOPE GETS A ROW, KEPT OR DROPPED, WITH ITS REASON. A list that
-- silently leaves firms out cannot be checked. `reason_code` is what the
-- funnel counts; `reason` is the sentence a person reads.
--
-- ONE MESSAGE PER MAILBOX, HELD BY THE SCHEMA. Sibling firms share mailboxes,
-- and `info@saas-fee.ch` sits under three Saastal companies. The partial
-- unique index below means no pin, rebuild or bug can put two kept firms on
-- one mailbox in the same list.
--
-- A CAMPAIGN'S STATE IS ITS TIMESTAMPS. No status column: planned, running,
-- paused, done and closed are read off the waves and the campaign's own dates,
-- the way `intel.draft` keeps its, so a stored word can never disagree with
-- what happened. Only `paused_at` and its reason are set directly, because the
-- bounce gate and the operator pause a campaign.
--
-- A WAVE GOES RENDER, TEST, APPROVE, SEND, AND THE SCHEMA HOLDS THE ORDER. The
-- checks on `crm.campaign_wave` refuse a test before a render, an approval
-- before a test, and a send before an approval, whatever the code above does.
-- `template_digest` fingerprints the files a wave was rendered from, so an
-- edit after the test makes the send refuse.
--
-- EVERY POST IS LOGGED BEFORE THE SERVER IS ASKED. `crm.outbound` is written
-- first and settled after, so a crash between the two leaves an attempt with
-- no outcome rather than a message nobody knows was sent; the next send for
-- that draft is refused until a person settles it. The same log counts the
-- 24-hour quota, tests and hand-typed letters included, and its Message-ID is
-- how a reply is matched to the firm actually written to.
--
-- `crm` POINTS AT `intel.draft`, NEVER THE REVERSE. A campaign's messages are
-- drafts the existing send stage posts, with every guard it already applies.
-- `clients` requires `scout`, so dropping the campaign tables orphans nothing.

CREATE TABLE IF NOT EXISTS crm.audience (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        TEXT NOT NULL UNIQUE,
    name        TEXT NOT NULL,
    rule        JSONB NOT NULL,
    rule_digest TEXT,
    built_at    TIMESTAMPTZ,
    -- Set when a campaign first posts from the list, after which a rebuild is
    -- refused: the waves already sent were cut from these rows.
    frozen_at   TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS crm.audience_member (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audience_id    BIGINT NOT NULL REFERENCES crm.audience (id) ON DELETE CASCADE,
    company_id     BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    contact_id     BIGINT REFERENCES core.contact (id) ON DELETE SET NULL,
    address        TEXT CHECK (address IS NULL OR address = lower(address)),
    language       TEXT,
    language_basis TEXT,
    segment        TEXT,
    score          NUMERIC(5,1),
    score_parts    JSONB NOT NULL DEFAULT '{}'::jsonb,
    verdict        TEXT NOT NULL CHECK (verdict IN ('kept', 'dropped')),
    reason_code    TEXT NOT NULL,
    reason         TEXT NOT NULL,
    covered_by     BIGINT REFERENCES crm.audience_member (id) ON DELETE SET NULL,
    -- An operator's decision, applied after the rule and kept across rebuilds:
    -- {verdict, language, contact_id, why, by, at}.
    pinned         JSONB,
    built_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (audience_id, company_id),
    CHECK (verdict = 'dropped' OR address IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS audience_member_list_idx
    ON crm.audience_member (audience_id, verdict, score DESC);
CREATE UNIQUE INDEX IF NOT EXISTS audience_member_one_mailbox_idx
    ON crm.audience_member (audience_id, address) WHERE verdict = 'kept';

CREATE TABLE IF NOT EXISTS crm.campaign (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            TEXT NOT NULL UNIQUE,
    name            TEXT NOT NULL,
    audience_id     BIGINT NOT NULL REFERENCES crm.audience (id) ON DELETE RESTRICT,
    programme_id    BIGINT REFERENCES crm.programme (id) ON DELETE SET NULL,
    templates       TEXT NOT NULL,
    strategy        TEXT NOT NULL,
    strategy_params JSONB NOT NULL DEFAULT '{}'::jsonb,
    pilot_size      INTEGER NOT NULL DEFAULT 10 CHECK (pilot_size >= 0),
    wave_size       INTEGER NOT NULL DEFAULT 25 CHECK (wave_size BETWEEN 1 AND 500),
    gap_days        INTEGER NOT NULL DEFAULT 7 CHECK (gap_days >= 0),
    start_on        DATE,
    bounce_ceiling  NUMERIC(4,3) NOT NULL DEFAULT 0.050
                    CHECK (bounce_ceiling BETWEEN 0 AND 1),
    settle_hours    INTEGER NOT NULL DEFAULT 48 CHECK (settle_hours >= 0),
    cooldown_days   INTEGER NOT NULL DEFAULT 180 CHECK (cooldown_days >= 0),
    enrolled_stages TEXT[] NOT NULL DEFAULT ARRAY['onboarding', 'testing', 'live'],
    planned_at      TIMESTAMPTZ,
    paused_at       TIMESTAMPTZ,
    paused_reason   TEXT,
    closed_at       TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS crm.campaign_wave (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id     BIGINT NOT NULL REFERENCES crm.campaign (id) ON DELETE CASCADE,
    number          INTEGER NOT NULL CHECK (number >= 1),
    pilot           BOOLEAN NOT NULL DEFAULT FALSE,
    label           TEXT NOT NULL DEFAULT '',
    planned_for     DATE,
    rendered_at     TIMESTAMPTZ,
    template_digest TEXT,
    tested_at       TIMESTAMPTZ,
    approved_at     TIMESTAMPTZ,
    approved_by     TEXT,
    sent_at         TIMESTAMPTZ,
    closed_at       TIMESTAMPTZ,
    UNIQUE (campaign_id, number),
    UNIQUE (id, campaign_id),
    CHECK (tested_at IS NULL OR (rendered_at IS NOT NULL AND tested_at >= rendered_at)),
    CHECK (approved_at IS NULL OR (tested_at IS NOT NULL AND approved_at >= tested_at)),
    CHECK (sent_at IS NULL OR approved_at IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS crm.campaign_message (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id    BIGINT NOT NULL,
    wave_id        BIGINT NOT NULL,
    member_id      BIGINT NOT NULL REFERENCES crm.audience_member (id) ON DELETE RESTRICT,
    draft_id       BIGINT REFERENCES intel.draft (id) ON DELETE SET NULL,
    variant        TEXT,
    dropped_at     TIMESTAMPTZ,
    dropped_reason TEXT,
    FOREIGN KEY (wave_id, campaign_id)
        REFERENCES crm.campaign_wave (id, campaign_id) ON DELETE CASCADE,
    UNIQUE (campaign_id, member_id)
);
CREATE INDEX IF NOT EXISTS campaign_message_wave_idx ON crm.campaign_message (wave_id);
CREATE UNIQUE INDEX IF NOT EXISTS campaign_message_draft_idx
    ON crm.campaign_message (draft_id) WHERE draft_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS crm.outbound (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         TEXT NOT NULL CHECK (kind IN ('message', 'test', 'letter')),
    address      TEXT NOT NULL,
    subject      TEXT NOT NULL,
    message_id   TEXT NOT NULL UNIQUE,
    draft_id     BIGINT REFERENCES intel.draft (id) ON DELETE SET NULL,
    wave_id      BIGINT REFERENCES crm.campaign_wave (id) ON DELETE SET NULL,
    variant      TEXT,
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    posted_at    TIMESTAMPTZ,
    failed_at    TIMESTAMPTZ,
    failure      TEXT,
    CHECK (posted_at IS NULL OR failed_at IS NULL)
);
CREATE INDEX IF NOT EXISTS outbound_window_idx ON crm.outbound (attempted_at DESC);
CREATE INDEX IF NOT EXISTS outbound_draft_idx
    ON crm.outbound (draft_id) WHERE draft_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS outbound_address_idx ON crm.outbound (lower(address));
