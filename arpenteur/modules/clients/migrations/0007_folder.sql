-- Folders: the client's own filing, laid over documents already stored.
--
-- Documents arrive in batches that mean something together — a consultation
-- dossier, a year's accounts, the papers for one audit — and the only
-- grouping on offer until now was `project_id`. That is the wrong shape
-- twice over. A batch of documents is not a piece of work, and creating a
-- project to hold ten PDFs puts a card on the board, a code on a contract
-- and a line in the pipeline for something nobody has agreed to do yet.
--
-- So a folder is what it sounds like and nothing more: a name, on one client,
-- that documents can be put in. It deliberately carries no status, no dates,
-- no budget and no code. The moment it carries any of those somebody will use
-- it as a project, and then there are two tables answering the same question
-- and drifting apart between them.
--
-- The two coexist on one document because they answer different questions:
-- the project says which piece of work a paper belongs to, the folder says
-- where it was filed. A document may have both, either, or neither.

CREATE TABLE IF NOT EXISTS crm.folder (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id  BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    -- As the operator would say it out loud: "the consultation dossier",
    -- "comptes 2025". Not a code, because nothing outside this table ever
    -- refers to a folder by name.
    name       TEXT NOT NULL,
    -- What the batch is and where it came from, for the person who opens it
    -- in eight months. Shown with the folder, never sent to a model: the
    -- documents speak for themselves and the note is filing, not evidence.
    note       TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One folder of a given name per client, compared without case. A second
-- "Cahier des charges" typed with a capital is somebody re-creating the
-- folder they already have, and answering that with two folders of the same
-- name is how a filing system stops being one.
CREATE UNIQUE INDEX IF NOT EXISTS folder_client_name_idx
    ON crm.folder (client_id, lower(name));

-- ON DELETE SET NULL, and this is the whole point of the column. Removing a
-- folder is a filing decision; it is not a decision to destroy the client's
-- papers. A delete that quietly took ten PDFs with it is the button nobody
-- dares press, and a filing system nobody dares tidy stops being used.
ALTER TABLE crm.attachment
    ADD COLUMN IF NOT EXISTS folder_id BIGINT
        REFERENCES crm.folder (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS attachment_folder_idx ON crm.attachment (folder_id);
