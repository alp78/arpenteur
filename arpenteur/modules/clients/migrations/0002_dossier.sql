-- What is known about a client, what to propose to them, and their papers.
--
-- The register says what a company is. The dossier says what it runs, who
-- decides, what is exposed and what has already been tried, and none of that
-- is in any register: it is assembled from public evidence, from the client's
-- own documents and from what was said in the room.
--
-- SECTIONS, NOT COLUMNS. A fixed schema of forty fields fits the first client
-- and is wrong for the second: a care foundation has a mail estate and a
-- resident record, a manufacturer has a shop floor and a stock system. So the
-- dossier is one row per named section, with the vocabulary in Python rather
-- than in a constraint here, so retiring a section leaves old rows readable.
--
-- PROVENANCE PER SECTION. Every section carries where it came from, in the
-- operator's own words. The distinction between observed, reported and
-- inferred is the difference between a diagnostic and a guess, and it is
-- exactly what gets lost when notes are one long textarea.
--
-- ADVICE IS VERSIONED, NEVER OVERWRITTEN. When the client asks in September
-- why March quoted what it quoted, the answer has to still exist along with
-- what it was computed from.
--
-- DOCUMENTS ARE CONTENT-ADDRESSED AND EXTRACTED ONCE. The file on disk is
-- named by its sha256, so the same document sent twice is one file. Extraction
-- fails on scanned paper, and a failure recorded once is answerable where one
-- that happens silently on every read is not.

CREATE TABLE IF NOT EXISTS crm.dossier (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id  BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    section    TEXT NOT NULL,
    body       TEXT,
    source     TEXT,
    author     TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (client_id, section)
);

CREATE INDEX IF NOT EXISTS dossier_client_idx ON crm.dossier (client_id);

CREATE TABLE IF NOT EXISTS crm.approach (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id      BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    source         TEXT NOT NULL DEFAULT 'model',
    model          TEXT,
    effort         TEXT,
    inputs_hash    TEXT,
    -- The named inputs. An approach that priced three days of work having read
    -- nothing is a different object from one that read the accounts, and the
    -- difference has to be visible afterwards.
    read_json      JSONB,
    situation      TEXT,
    opening        TEXT,
    points_json    JSONB,
    services_json  JSONB,
    pricing_json   JSONB,
    risks_json     JSONB,
    questions_json JSONB,
    -- A human took this and used it. Generated advice nobody acted on is not
    -- the same thing as advice that went into a proposal.
    accepted_at    TIMESTAMPTZ,
    note           TEXT
);

CREATE INDEX IF NOT EXISTS approach_client_idx
    ON crm.approach (client_id, created_at DESC);

CREATE TABLE IF NOT EXISTS crm.attachment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    project_id    BIGINT REFERENCES crm.project (id) ON DELETE SET NULL,
    -- As the client named it: "Rapport 2025 VF (2).pdf" is how they will refer
    -- to it on the phone.
    filename      TEXT NOT NULL,
    media_type    TEXT,
    bytes         BIGINT NOT NULL,
    sha256        TEXT NOT NULL,
    kind          TEXT,
    note          TEXT,
    text          TEXT,
    text_chars    INTEGER,
    extracted_at  TIMESTAMPTZ,
    extract_error TEXT,
    uploaded_by   TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Per client rather than globally: two clients may legitimately hold the
    -- same standard contract, and merging those across a client boundary would
    -- be a confidentiality failure rather than a deduplication.
    UNIQUE (client_id, sha256)
);

CREATE INDEX IF NOT EXISTS attachment_client_idx
    ON crm.attachment (client_id, created_at DESC);
CREATE INDEX IF NOT EXISTS attachment_project_idx ON crm.attachment (project_id);

-- What to revise before walking into the room. A client's file accumulates
-- vocabulary faster than anyone absorbs it, and the difference between knowing
-- a term cold and half-knowing it shows in a meeting where the client's own
-- expert is present.
CREATE TABLE IF NOT EXISTS crm.briefing (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    model       TEXT,
    effort      TEXT,
    inputs_hash TEXT,
    read_json   JSONB,
    orientation TEXT,
    agenda_json JSONB
);

CREATE INDEX IF NOT EXISTS briefing_client_idx
    ON crm.briefing (client_id, created_at DESC);

CREATE TABLE IF NOT EXISTS crm.glossary (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    term        TEXT NOT NULL,
    category    TEXT,
    expansion   TEXT,
    what_it_is  TEXT,
    -- Why it appears in THIS client's file. The part a general glossary cannot
    -- give you and the only part worth reading twice.
    why_here    TEXT,
    must_know   TEXT,
    question    TEXT,
    -- A standard number or a legal article, named rather than linked: a name
    -- can be verified and an invented URL looks exactly like a real one.
    reference   TEXT,
    priority    TEXT,
    -- The person's, and never written by a run. Regenerating after the client
    -- sends a document must not reset an evening's revision.
    known       BOOLEAN NOT NULL DEFAULT FALSE,
    note        TEXT,
    first_seen  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    briefing_id BIGINT REFERENCES crm.briefing (id) ON DELETE SET NULL,
    UNIQUE (client_id, term)
);

CREATE INDEX IF NOT EXISTS glossary_client_idx
    ON crm.glossary (client_id, category, term);
