-- A programme: one endeavour, many companies, each at its own stage.
--
-- Two shapes of work already exist here and neither fits. `intel.prospect`
-- gives a company one global state, so a company cannot be at `testing` in one
-- effort and untouched in another; a second effort would overwrite the first's
-- pipeline. `crm.project` is an engagement for one client, with a code, a
-- billing arrangement, a budget and invoices behind it, and creating forty of
-- them to send an application to forty agencies would put forty cards on a
-- board and forty lines in a pipeline for work nobody has agreed to do.
--
-- So: a programme is the endeavour, a member is one company inside it, and the
-- member carries the stage. Sending a handover application to the régies of
-- Suisse romande is one programme with fifty members; the same agency can be a
-- member of a second programme next year without either knowing about the
-- other.
--
-- A MEMBER IS A COMPANY, NOT A CLIENT. The same reasoning `intel.prospect`
-- records: most of a survey will never become a client, and here a refusal is
-- precisely a member that never converts. Keying on the client would mean the
-- outcome worth studying is the one the schema cannot hold. Where a member has
-- become a client the console looks that up, because it is allowed to know
-- about both modules where this schema is not.
--
-- STAGES ARE DATA, PER PROGRAMME. Sectors, segments and dossier sections are
-- all the operator's own words, and a rollout's stages are no different: the
-- next programme may recruit partners or run a pilot, and neither speaks of
-- `onboarding`. `stage_notes` carries the gloss for the same reason the board's
-- columns carry one, that a column called `replied` with nothing under it gets
-- used for three different things by the end of a month and then the counts say
-- nothing.
--
-- NO STATE HISTORY TABLE HERE. `audit.state_change` names its subject as text
-- and holds no foreign key, which is what lets a later module log to it. A move
-- writes `entity = 'programme_member'` there, so "how long has this card sat in
-- this column" is answered by the query the board already runs, and the history
-- outlives the programme if it is deleted.

CREATE TABLE IF NOT EXISTS crm.programme (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- FLATCHECK. Its own reference for the same reason a project has one: it
    -- outlives the conversation that started it and has to be nameable in a
    -- contract, a file and a sentence spoken out loud.
    code        TEXT NOT NULL UNIQUE,
    name        TEXT NOT NULL,
    -- What the endeavour is, in the operator's words. Standing context, not an
    -- event: distinct from the feedback log, which is things that happened.
    what        TEXT,
    status      TEXT NOT NULL DEFAULT 'running',
    -- The pipeline, in order. The board draws one column per entry, left to
    -- right, so the array's order is the reading order and not an accident.
    stages      TEXT[] NOT NULL DEFAULT ARRAY[
        'selected', 'contacted', 'replied', 'onboarding',
        'testing', 'live', 'refused', 'parked'
    ],
    -- stage name -> one line saying what belongs in it.
    stage_notes JSONB NOT NULL DEFAULT '{}'::jsonb,
    started_at  DATE,
    -- The end the whole thing is pointed at, kept on the programme rather than
    -- logged as an event: moving a release date should move what the page says,
    -- and a row written on the day somebody typed it goes quietly stale.
    released_at DATE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS programme_status_idx ON crm.programme (status);

CREATE TABLE IF NOT EXISTS crm.programme_member (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_id BIGINT NOT NULL REFERENCES crm.programme (id) ON DELETE CASCADE,
    company_id   BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    -- One of the programme's own `stages`. Not a foreign key and not an enum:
    -- the valid set is a column on another row and changes when the operator
    -- edits it, so the check lives in the store where it can say which stages
    -- were on offer.
    stage        TEXT NOT NULL DEFAULT 'selected',
    -- Who at the agency this goes through, as it would be said out loud.
    -- `core.contact` holds addresses the survey found; this holds the person a
    -- human decided to deal with, which is a different fact.
    contact      TEXT,
    note         TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ,
    -- Adding a company twice gives back the member already there. A second row
    -- would put the same agency in two columns of one board, and a card you can
    -- drag in one place while a stale copy sits in another is worse than no
    -- board.
    UNIQUE (programme_id, company_id)
);

CREATE INDEX IF NOT EXISTS programme_member_stage_idx
    ON crm.programme_member (programme_id, stage);
-- "Which programmes is this company in", asked from a company page.
CREATE INDEX IF NOT EXISTS programme_member_company_idx
    ON crm.programme_member (company_id);

-- What a member said back. The testing phase produces this and it has nowhere
-- else to go.
--
-- WHY IT IS NOT ONE OF THE TWO LOGS THAT ALREADY EXIST. `crm.interaction`
-- requires a `client_id`, and most members are not clients; forcing one would
-- mean inventing a client record for an agency that refused. `intel.note` is
-- keyed on the company, so the same agency's feedback on two different
-- programmes would sit in one list with nothing to separate them. The scoping
-- here is genuinely programme x company, and neither table can express it.
--
-- Deliberately thin: a kind, a body, a date and an author. No status, no
-- assignee, no severity, no priority. The moment it carries those somebody will
-- run the bug list from it, and it will drift from whatever actually tracks the
-- bugs. This records what a tester said, and says when.
CREATE TABLE IF NOT EXISTS crm.programme_feedback (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   BIGINT NOT NULL REFERENCES crm.programme_member (id) ON DELETE CASCADE,
    -- 'note' | 'bug' | 'request' | 'praise'. Text rather than an enum, for the
    -- reason every other kind column here is text.
    kind        TEXT NOT NULL DEFAULT 'note',
    body        TEXT NOT NULL,
    -- When it was said, which is not when it was typed. A call reported the
    -- next morning belongs on the day of the call.
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    author      TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS programme_feedback_member_idx
    ON crm.programme_feedback (member_id, occurred_at DESC);
