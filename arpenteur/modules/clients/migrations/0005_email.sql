-- Correspondence imported from a mailbox, and what it was matched to.
--
-- The rule this schema exists to enforce is that nothing is filed silently. A
-- message arrives here first, with whatever the matcher made of it, and
-- becomes a `crm.interaction` only when a person accepts it. Every established
-- tool surveyed either files everything from a known address, which puts a
-- lunch invitation in a client's project history, or files nothing, which is
-- why people keep their real record in Outlook. The queue is the difference.
--
-- **Envelopes for everything kept, bodies only for what matched.** This is
-- somebody's personal mailbox and most of it has nothing to do with any
-- client. A subject line is metadata and is what makes the queue reviewable at
-- all; the text of a private message is content, and copying it into a CRM
-- because it happened to be in the same folder is not something the owner
-- asked for. So `body` stays null until either the matcher found a company or
-- a person filed the message by hand, at which point it is fetched.
--
-- `message_id` is globally unique rather than unique per company. The same
-- message cannot be imported twice under two different matches, which is the
-- failure that produces two copies of a thread in a timeline.

CREATE TABLE IF NOT EXISTS crm.email_message (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- RFC 5322 Message-ID, verbatim, angle brackets and all. Deduplication
    -- rests entirely on this: an IMAP UID is unique only within one folder of
    -- one mailbox and changes when a folder is rebuilt, so it is recorded for
    -- refetching and never for identity.
    message_id  TEXT NOT NULL UNIQUE,
    -- The root of the References chain, which is as close as mail comes to a
    -- thread. Not a foreign key to anything: two chains a human would call one
    -- conversation will never say so in a header, and a `thread` table would
    -- promise a grouping the data cannot support.
    thread_key  TEXT,
    folder      TEXT NOT NULL,
    uid         BIGINT,
    -- 'in' or 'out', read from the folder rather than inferred from the
    -- addresses: a person who copies themselves on an outgoing message would
    -- otherwise have it filed as incoming.
    direction   TEXT NOT NULL,
    sent_at     TIMESTAMPTZ,
    subject     TEXT,
    from_name   TEXT,
    from_email  TEXT,
    to_emails   TEXT[] NOT NULL DEFAULT '{}',
    cc_emails   TEXT[] NOT NULL DEFAULT '{}',
    -- Null until the message matched or a person filed it. See the header.
    body        TEXT,
    body_kind   TEXT,
    -- pending | filed | ignored
    state       TEXT NOT NULL DEFAULT 'pending',
    -- What the matcher proposed, which a person may overrule. ON DELETE SET
    -- NULL rather than CASCADE: removing a company should not silently delete
    -- correspondence that a human has already read and accepted.
    company_id  BIGINT REFERENCES core.company (id) ON DELETE SET NULL,
    -- 'address', 'domain', 'link' or 'manual', and the value it matched on, so
    -- the review page can say why it is proposing this client rather than
    -- asking the reader to take it on faith.
    match_method TEXT,
    match_value  TEXT,
    interaction_id BIGINT REFERENCES crm.interaction (id) ON DELETE SET NULL,
    fetched_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_at  TIMESTAMPTZ,
    decided_by  TEXT
);

CREATE INDEX IF NOT EXISTS email_message_queue_idx
    ON crm.email_message (state, sent_at DESC);
CREATE INDEX IF NOT EXISTS email_message_company_idx
    ON crm.email_message (company_id, sent_at DESC);
CREATE INDEX IF NOT EXISTS email_message_thread_idx
    ON crm.email_message (thread_key);

-- Which addresses and domains belong to which company.
--
-- The survey learns a company's postal address from the register and its
-- officers from the notices, and neither of those says who mails whom. On a
-- fresh database nothing matches, so the first message from a new client is
-- filed by hand; what makes that a one-off rather than a chore is that the act
-- of filing is recorded here, and the rest of the thread and everything after
-- it matches on its own.
--
-- A domain is learned from a human filing a message, and only when it is not a
-- free-mail provider. That is a small inference from a deliberate act, it is
-- visible on the client page, and it is reversible; the alternative is asking
-- somebody to type the same association once per message.
--
-- UNIQUE on (kind, value) and not on (company_id, kind, value): a domain
-- belongs to one company. Where a group shares a mail domain across several
-- legal entities the association is genuinely ambiguous, and refusing the
-- second write surfaces that as a conflict to be decided rather than as two
-- rules that quietly disagree.
CREATE TABLE IF NOT EXISTS crm.email_link (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    -- 'address' | 'domain'
    kind       TEXT NOT NULL,
    value      TEXT NOT NULL,
    -- 'filed' when a person's decision taught it, 'manual' when typed.
    source     TEXT NOT NULL DEFAULT 'filed',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (kind, value)
);

CREATE INDEX IF NOT EXISTS email_link_company_idx
    ON crm.email_link (company_id);
