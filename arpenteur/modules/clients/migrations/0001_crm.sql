-- The work that follows a yes.
--
-- Everything in the scout is about finding companies. This is about the ones
-- that answered, and it is a different job: a client has projects, a project
-- has a history, and the history has to survive an audit rather than merely
-- jog a memory.
--
-- It references `core.company` and nothing references it. That direction is
-- the module boundary: a deployment that licenses only the scout drops this
-- schema and loses nothing upstream.
--
-- Four decisions, each taken against how the established professional-services
-- tools do it.
--
-- ONE INTERACTION LOG, NOT TWO. The compliance audit trail and the narrative
-- client timeline are the same stream of events rendered for two audiences,
-- and tools that build them separately drift. The drift is always discovered
-- during the audit. So there is one table, written once and projected
-- differently: the client page reads it as a story, the calendar as a diary,
-- an export as a record.
--
-- A PLANNED INTERACTION IS AN INTERACTION. A meeting next Tuesday and one last
-- Tuesday differ by a date and a state, not by their nature, so the diary and
-- the history are the same query and a meeting cannot be in one and missing
-- from the other.
--
-- CANCELLED IS A STATE; DELETING IS A DIFFERENT CORRECTION. Cancelled says a
-- thing was true and did not happen, and keeps its row. Deleting says it was
-- never true, and leaves a tombstone naming what went and why. The schema
-- originally allowed only the first, on the grounds that an audit trail with a
-- delete button is a diary. That was half right, and the half it got wrong
-- cost more: rows describing a meeting that never existed were written into a
-- live record and there was no way to take them out. A log that cannot be
-- corrected is not more truthful, only more confident.
--
-- THE CLIENT IS THE COMPANY, NOT A COPY OF IT. Promoting a prospect keeps the
-- register entry, the officers, the research and the notes. The comparisons
-- call the alternative the handoff gap: a system that stops at "closed won"
-- makes the first day of an engagement a copy-paste job.

CREATE SCHEMA IF NOT EXISTS crm;

CREATE TABLE IF NOT EXISTS crm.client (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL UNIQUE REFERENCES core.company (id) ON DELETE CASCADE,
    -- Human reference, used on invoices and in conversation: BOIS-GENTIL.
    -- Unique so it can be quoted without ambiguity, and editable because the
    -- generated form is a starting point rather than a decision.
    code       TEXT NOT NULL UNIQUE,
    status     TEXT NOT NULL DEFAULT 'active',
    since      DATE,
    owner      TEXT,
    -- Standing context: what this relationship is, who decides, how they buy.
    -- Distinct from an interaction, which is something that happened.
    brief      TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS client_status_idx ON crm.client (status);

CREATE TABLE IF NOT EXISTS crm.project (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id  BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    -- BOIS-GENTIL-01. Its own identifier, because a project outlives the
    -- conversation that started it and has to be referable in an invoice, a
    -- contract and a file name.
    code       TEXT NOT NULL UNIQUE,
    name       TEXT NOT NULL,
    status     TEXT NOT NULL DEFAULT 'proposed',
    -- How it is paid for. What separates a tool that fits professional
    -- services from one that does not: fixed fee, time and materials and
    -- retainer are genuinely different agreements and one budget number cannot
    -- represent all three.
    billing    TEXT,
    budget     NUMERIC(14, 2),
    currency   TEXT DEFAULT 'CHF',
    summary    TEXT,
    started_at DATE,
    due_at     DATE,
    closed_at  DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS project_client_idx ON crm.project (client_id, status);

-- Everything that happened, or is going to. The audit trail, the timeline and
-- the calendar, which are one thing seen from three angles.
CREATE TABLE IF NOT EXISTS crm.interaction (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    -- Nullable: an interaction can concern the relationship rather than any one
    -- project, and forcing a project on it would invent an association.
    project_id  BIGINT REFERENCES crm.project (id) ON DELETE SET NULL,
    kind        TEXT NOT NULL,
    state       TEXT NOT NULL DEFAULT 'done',
    occurred_at TIMESTAMPTZ NOT NULL,
    ends_at     TIMESTAMPTZ,
    subject     TEXT,
    body        TEXT,
    direction   TEXT,
    with_whom   TEXT,
    author      TEXT,
    source      TEXT NOT NULL DEFAULT 'manual',
    -- The mail Message-ID, so importing the same message twice is not two
    -- rows. Every established tool surveyed loses this and duplicates
    -- correspondence on re-import; it costs one column not to.
    external_id TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (client_id, external_id)
);

CREATE INDEX IF NOT EXISTS interaction_client_idx
    ON crm.interaction (client_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS interaction_project_idx
    ON crm.interaction (project_id, occurred_at DESC);
-- The calendar reads forward from today across every client at once, so the
-- date leads this index rather than the client.
CREATE INDEX IF NOT EXISTS interaction_diary_idx
    ON crm.interaction (occurred_at) WHERE state = 'planned';
