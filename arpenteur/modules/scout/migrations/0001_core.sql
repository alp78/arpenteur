-- The scout: canonical companies, and what the register says about them.
--
-- Two schemas, because they answer different questions and change at
-- different rates. `core` is what a company IS: the register's own facts,
-- corrected only when the register is. `intel` is what we have observed and
-- concluded about it, which is ours, cheap to rebuild, and wrong more often.
-- Keeping them apart means a bad classification run can be truncated without
-- anyone worrying about the register data underneath.
--
-- Every table holding a fact about the outside world carries its own
-- provenance: source_url, method, fetched_at. Not a provenance table, because
-- the question "where did this come from and when" is asked of single rows and
-- a join would let a row exist without an answer. Under the nLPD that answer
-- is the difference between a defensible dataset and an indefensible one.
--
-- Nothing here references anything downstream. `crm` and `commercial` may
-- point at a company; a company never points back. That one-way rule is what
-- makes the sales module removable: dropping its schema cannot orphan a row
-- here, and Postgres would refuse the drop if it could.

CREATE SCHEMA IF NOT EXISTS core;
CREATE SCHEMA IF NOT EXISTS intel;

-- A legal entity as the commercial register knows it.
CREATE TABLE IF NOT EXISTS core.company (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The UID (CHE-...) is the federal identifier and the natural key. Kept as
    -- the key a human quotes, rather than hidden behind a surrogate: it is
    -- readable in a log and printable on an invoice.
    uid                  TEXT NOT NULL UNIQUE,
    chid                 TEXT,
    ehraid               BIGINT,
    name                 TEXT NOT NULL,
    legal_form_uid       TEXT,
    legal_form_label     TEXT,
    legal_seat           TEXT,
    legal_seat_id        INTEGER,
    canton               TEXT,
    status               TEXT,
    -- The registered purpose. The classify stage reads nothing else, so a
    -- company with no purpose text is simply not classifiable yet.
    purpose              TEXT,
    address_json         JSONB,
    capital              NUMERIC(18, 2),
    capital_currency     TEXT,
    cantonal_excerpt_url TEXT,
    zefix_detail_url     TEXT,
    source_url           TEXT,
    method               TEXT,
    fetched_at           TIMESTAMPTZ,
    -- Set once, on first insert: lets a later run tell a new registration from
    -- a company that was merely re-swept.
    first_seen           TIMESTAMPTZ NOT NULL DEFAULT now(),
    hydrated_at          TIMESTAMPTZ,
    content_hash         TEXT,
    stale_since          TIMESTAMPTZ,
    last_mutation_date   DATE
);

CREATE INDEX IF NOT EXISTS company_canton_idx ON core.company (canton);
CREATE INDEX IF NOT EXISTS company_form_idx ON core.company (legal_form_uid);
CREATE INDEX IF NOT EXISTS company_hydrated_idx ON core.company (hydrated_at);
CREATE INDEX IF NOT EXISTS company_stale_idx ON core.company (stale_since)
    WHERE stale_since IS NOT NULL;
-- Name search, two ways, because they answer different questions. Trigram
-- handles "I typed it slightly wrong" and is what party resolution will lean
-- on later; full text handles "a word from the purpose". Neither was possible
-- on the old store, where a name search was a LIKE over 184'939 rows.
CREATE INDEX IF NOT EXISTS company_name_trgm_idx ON core.company
    USING gin (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS company_search_idx ON core.company
    USING gin (to_tsvector('french', coalesce(name, '') || ' ' || coalesce(purpose, '')));

-- People named in the register's own notices. Public sources only.
CREATE TABLE IF NOT EXISTS core.person (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    full_name  TEXT NOT NULL,
    role       TEXT,
    -- The disambiguators the notices carry: "de Coldrerio, à Lausanne". Stored
    -- because they are what will resolve one human across several boards, and
    -- a name alone cannot.
    origin     TEXT,
    domicile   TEXT,
    signature  TEXT,
    last_seen_date DATE,
    source_url TEXT,
    method     TEXT,
    fetched_at TIMESTAMPTZ,
    UNIQUE (company_id, full_name, role)
);

CREATE INDEX IF NOT EXISTS person_company_idx ON core.person (company_id);
CREATE INDEX IF NOT EXISTS person_name_trgm_idx ON core.person
    USING gin (full_name gin_trgm_ops);

-- A resolved point of contact. `method` records how it was obtained
-- (published, pattern, provider) and `status` whether it verified.
CREATE TABLE IF NOT EXISTS core.contact (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id   BIGINT REFERENCES core.person (id) ON DELETE CASCADE,
    company_id  BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    kind        TEXT NOT NULL,
    value       TEXT NOT NULL,
    status      TEXT,
    source_url  TEXT,
    method      TEXT,
    fetched_at  TIMESTAMPTZ,
    -- Honoured before anything is ever drafted, and never cleared by a later
    -- run that finds the address published again. A person said no;
    -- rediscovering the address is not consent.
    suppressed  BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (company_id, kind, value)
);

CREATE INDEX IF NOT EXISTS contact_company_idx ON core.contact (company_id);

-- The register's own change notices, kept verbatim.
CREATE TABLE IF NOT EXISTS core.publication (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id   BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    sogc_id      BIGINT,
    sogc_date    DATE,
    journal_id   BIGINT,
    journal_date DATE,
    canton       TEXT,
    -- The notice as filed, tags and all. Reparsing stored strings is seconds
    -- where re-fetching them is a day of polite traffic, so the raw text is
    -- the asset and the parse is disposable.
    message      TEXT NOT NULL,
    source_url   TEXT,
    method       TEXT,
    fetched_at   TIMESTAMPTZ,
    UNIQUE (company_id, sogc_id)
);

CREATE INDEX IF NOT EXISTS publication_company_idx ON core.publication (company_id);
CREATE INDEX IF NOT EXISTS publication_date_idx ON core.publication (sogc_date);
