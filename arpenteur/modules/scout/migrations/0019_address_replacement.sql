-- Looking again for a firm whose address bounced.
--
-- A search records what it learned about the firm's mail domains and what it
-- tried, and each address it turned up is a proposal for a person to accept
-- or refuse. A refused proposal stays, so the next search never offers it
-- again; an accepted one has become a row of core.contact and points at it.
-- Nothing here is written to by a list or a campaign: a proposal reaches a
-- mailbox only after a person accepted it.
CREATE TABLE IF NOT EXISTS intel.address_search (
    company_id  BIGINT PRIMARY KEY REFERENCES core.company (id) ON DELETE CASCADE,
    replaces    TEXT[] NOT NULL DEFAULT '{}',
    domains     JSONB NOT NULL DEFAULT '[]'::jsonb,
    tried       JSONB NOT NULL DEFAULT '[]'::jsonb,
    searches    INTEGER NOT NULL DEFAULT 0,
    pages       INTEGER NOT NULL DEFAULT 0,
    searched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS intel.address_proposal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id  BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    address     TEXT NOT NULL,
    kind        TEXT NOT NULL,
    found_by    TEXT NOT NULL CHECK (found_by IN ('page', 'listing', 'inferred')),
    source_url  TEXT,
    verdict     TEXT,
    note        TEXT NOT NULL DEFAULT '',
    found_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    decision    TEXT CHECK (decision IN ('accepted', 'refused')),
    decided_at  TIMESTAMPTZ,
    decided_by  TEXT,
    contact_id  BIGINT REFERENCES core.contact (id) ON DELETE SET NULL,
    CHECK ((decision IS NULL) = (decided_at IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS address_proposal_once
    ON intel.address_proposal (company_id, lower(address));
