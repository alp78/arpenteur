-- One human, across the several companies that name them.
--
-- `core.person` is one row per (company, name, role): what a notice said,
-- where it said it. That is the right shape for a source and the wrong shape
-- for a question. "Who else does this director sit with" cannot be asked of it,
-- because the same person is thirteen unrelated rows.
--
-- So a party is the resolved human, and a party_role is the edge. The source
-- rows are untouched: a resolution can be redone, and it must never be able to
-- destroy what the register actually published.
--
-- WHY THE RESOLUTION IS CONSERVATIVE. Two people wrongly split is a missing
-- edge, which is a gap. Two people wrongly merged is a false statement about a
-- named individual, in a tool that goes on to suggest writing to them. The
-- first is recoverable and the second is not, so the rule below splits when it
-- is unsure and records how sure it was.
--
-- The register's own disambiguators are what make it possible at all: a notice
-- writes "Boccard Christian, de France, à Gaillard", and the origin is a legal
-- attribute of a Swiss person that does not change with a house move. The
-- domicile does, so it is stored and not keyed on.

CREATE TABLE IF NOT EXISTS core.party (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- person | organisation. A company can hold a mandate; those rows are
    -- kept out of `person` today, and the column is here so that the day they
    -- arrive they are not silently counted as human directors.
    kind       TEXT NOT NULL DEFAULT 'person',
    full_name  TEXT NOT NULL,
    -- The comparison form: unaccented, lowercased, punctuation dropped. Stored
    -- rather than computed on read so the unique constraint can use it.
    sort_name  TEXT NOT NULL,
    origin     TEXT,
    -- The most recent domicile seen. Descriptive only: people move, and a
    -- resolution keyed on where somebody lived in 2019 would split them from
    -- themselves in 2026.
    domicile   TEXT,
    -- How the identity was decided, and how much to believe it.
    --   single           one row, nothing merged, so nothing is claimed
    --   name-and-origin  same name and same registered origin
    --   sole-origin      same name, one origin known among them, rest silent
    --   name-only        same name, no origin anywhere: the weakest kind
    --   manual           a person decided
    method     TEXT NOT NULL DEFAULT 'name-and-origin',
    confidence REAL NOT NULL DEFAULT 0.9,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    UNIQUE (sort_name, origin, method)
);

CREATE INDEX IF NOT EXISTS party_name_trgm_idx ON core.party
    USING gin (full_name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS party_sort_idx ON core.party (sort_name);

-- The edge: this person, at this company, in this role.
CREATE TABLE IF NOT EXISTS core.party_role (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id   BIGINT NOT NULL REFERENCES core.party (id) ON DELETE CASCADE,
    company_id BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    -- The `person` row this was resolved from, so an edge can always be taken
    -- back to the notice that asserted it. ON DELETE SET NULL rather than
    -- CASCADE: a reparse that withdraws a person row should leave the edge
    -- visibly unsourced rather than make it vanish without trace.
    person_id  BIGINT REFERENCES core.person (id) ON DELETE SET NULL,
    role       TEXT,
    signature  TEXT,
    -- When the role opened and closed, as the notices tell it. Both nullable:
    -- most of what is held is a snapshot of the latest notice, and a date
    -- invented to fill the column would be worse than an empty one.
    valid_from DATE,
    valid_to   DATE,
    source_url TEXT,
    method     TEXT NOT NULL DEFAULT 'shab',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (party_id, company_id, role)
);

CREATE INDEX IF NOT EXISTS party_role_party_idx ON core.party_role (party_id);
CREATE INDEX IF NOT EXISTS party_role_company_idx ON core.party_role (company_id);
-- Board overlap walks company -> party -> company, so both directions of that
-- join are read hot and both get an index.
CREATE INDEX IF NOT EXISTS party_role_pair_idx
    ON core.party_role (company_id, party_id);
