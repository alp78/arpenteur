-- What we have observed and concluded about a company, as opposed to what the
-- register says it is.
--
-- Everything here is ours, cheap to rebuild and wrong more often than `core`,
-- which is why it lives in its own schema: a bad classification run can be
-- truncated without anyone having to think about the register data underneath.
--
-- The rule that shapes these tables: a human's judgement outranks a model's,
-- permanently. Every table that a stage writes carries a `source` of `model`
-- or `manual`, and every writer refuses to overwrite a manual row. Without
-- that a console is a display rather than a tool, because correcting a label
-- would feel like work and be silently undone by the next run.

-- How a company was sorted. Several at once is normal: a regulated laboratory
-- is both compliance-sector and data-driven, and forcing a choice at
-- classification time would throw away the more useful half.
CREATE TABLE IF NOT EXISTS intel.segment (
    company_id    BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    segment       TEXT NOT NULL,
    confidence    REAL,
    rationale     TEXT,
    model         TEXT,
    classified_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    source        TEXT NOT NULL DEFAULT 'model',
    PRIMARY KEY (company_id, segment)
);

CREATE INDEX IF NOT EXISTS segment_name_idx ON intel.segment (segment);
CREATE INDEX IF NOT EXISTS segment_manual_idx ON intel.segment (company_id)
    WHERE source = 'manual';

-- What a company's own website says, read once and re-read only when it moves.
CREATE TABLE IF NOT EXISTS intel.site (
    company_id   BIGINT PRIMARY KEY REFERENCES core.company (id) ON DELETE CASCADE,
    status       TEXT,
    url          TEXT,
    confidence   REAL,
    language     TEXT,
    summary      TEXT,
    offerings    JSONB,
    signals      JSONB,
    partnerships JSONB,
    tech_stack   JSONB,
    size_hint    TEXT,
    source_url   TEXT,
    method       TEXT,
    fetched_at   TIMESTAMPTZ,
    model        TEXT,
    searches     INTEGER,
    fetches      INTEGER,
    -- Solvency and enforcement material, held apart and never shown to the
    -- stage that writes an approach. The surest way to keep it out of a
    -- message is for the writer never to have seen it.
    restricted   JSONB,
    -- What the research read. A score is stale when this moves, which is how a
    -- re-run touches exactly the companies whose evidence changed.
    content_hash TEXT,
    reached_at   TIMESTAMPTZ,
    reach_pages  INTEGER
);

CREATE INDEX IF NOT EXISTS site_status_idx ON intel.site (status);

-- How well a company fits the campaign, and what to open with.
CREATE TABLE IF NOT EXISTS intel.fit (
    company_id BIGINT PRIMARY KEY REFERENCES core.company (id) ON DELETE CASCADE,
    score      INTEGER,
    band       TEXT,
    reasoning  TEXT,
    advice     TEXT,
    against    JSONB,
    matched    JSONB,
    source     TEXT NOT NULL DEFAULT 'model',
    model      TEXT,
    -- The two inputs, hashed. Rewriting the campaign brief or re-researching a
    -- site invalidates exactly the scores taken against the old ones, and
    -- nothing else. A manual score is never stale: a person is not an input
    -- that expired.
    brief_hash TEXT,
    site_hash  TEXT,
    scored_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS fit_score_idx ON intel.fit (score DESC);
CREATE INDEX IF NOT EXISTS fit_band_idx ON intel.fit (band);

-- Where a company stands in the campaign, and the follow-up log that goes with
-- it. Both keyed on the company rather than on a client, because most of the
-- survey will never become one.
CREATE TABLE IF NOT EXISTS intel.prospect (
    company_id  BIGINT PRIMARY KEY REFERENCES core.company (id) ON DELETE CASCADE,
    state       TEXT NOT NULL DEFAULT 'new',
    owner       TEXT,
    next_action TEXT,
    next_at     DATE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS prospect_state_idx ON intel.prospect (state);
CREATE INDEX IF NOT EXISTS prospect_next_idx ON intel.prospect (next_at);

CREATE TABLE IF NOT EXISTS intel.note (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id  BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    kind        TEXT NOT NULL DEFAULT 'note',
    body        TEXT NOT NULL,
    author      TEXT,
    -- When it happened, which is not when it was typed. A call logged the next
    -- morning belongs on the day of the call.
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS note_company_idx ON intel.note (company_id, occurred_at);

-- Proposals for a human to read, edit and decide on. `sent_at` stays null
-- unless a person acts; nothing in this pipeline sends anything by itself.
-- Swiss law (LCD art. 3 al. 1 let. o) draws its line at mass advertising
-- email, and the defence against crossing it is that the software has no
-- mechanism, not that nobody clicks the button.
CREATE TABLE IF NOT EXISTS intel.draft (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id  BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    person_id   BIGINT REFERENCES core.person (id) ON DELETE SET NULL,
    language    TEXT,
    subject     TEXT,
    body        TEXT,
    model       TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMPTZ,
    sent_at     TIMESTAMPTZ
);

-- Bookkeeping for the sweep and the change feed, so neither repeats work.
CREATE TABLE IF NOT EXISTS intel.sweep (
    canton         TEXT NOT NULL,
    legal_form_uid TEXT NOT NULL,
    prefix         TEXT NOT NULL,
    result_count   INTEGER,
    deepened       BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (canton, legal_form_uid, prefix)
);

CREATE TABLE IF NOT EXISTS intel.sync_day (
    sogc_date  DATE PRIMARY KEY,
    notices    INTEGER,
    tracked    INTEGER,
    inserted   INTEGER,
    updated    INTEGER,
    deletions  INTEGER,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
