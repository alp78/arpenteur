-- Every transition of every entity, kept.
--
-- Today a status is a column and a change is an overwrite. `intel.prospect`
-- says a company is at `contacted` and cannot say since when; `crm.project`
-- says `active` and cannot say how long it was `proposed`. The board made that
-- visible the moment it drew columns: the question a column of eight cards
-- provokes is "how long has that one been sitting there", and the answer was
-- nowhere.
--
-- WHY IT HAS NO FOREIGN KEYS, ON PURPOSE. An audit row about a project that
-- has since been deleted is exactly the row worth having, and a foreign key
-- would take it away at the moment it became interesting. The entity is named
-- as text and its id as a number, so this table can outlive what it describes
-- and can record a transition in a schema that is not installed.
--
-- That same absence is what lets it live here without coupling anything.
-- `audit` belongs to the scout because every module requires the scout, so
-- every module may write to it; and because it points at nothing, nothing
-- points back, and the one-way rule is untouched.

CREATE SCHEMA IF NOT EXISTS audit;

CREATE TABLE IF NOT EXISTS audit.state_change (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 'prospect' | 'client' | 'project' | 'interaction' | anything a later
    -- module records. Deliberately not an enum: a table that has to be
    -- migrated before a module can log to it is a table modules avoid.
    entity     TEXT NOT NULL,
    entity_id  BIGINT NOT NULL,
    -- The company this concerns, where there is one, so a company's whole
    -- history can be read without knowing which tables it passed through.
    -- Nullable and unconstrained, for the reason above.
    company_id BIGINT,
    from_state TEXT,
    to_state   TEXT NOT NULL,
    -- Who moved it and why. `by` is a name rather than a user id because this
    -- system has one operator; the column is here so that it can stop being
    -- true without a migration.
    by         TEXT,
    reason     TEXT,
    at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS state_change_entity_idx
    ON audit.state_change (entity, entity_id, at DESC);
CREATE INDEX IF NOT EXISTS state_change_company_idx
    ON audit.state_change (company_id, at DESC);
-- "What moved this week" reads the whole table by date, which is the query
-- behind any funnel or cycle-time report.
CREATE INDEX IF NOT EXISTS state_change_at_idx ON audit.state_change (at DESC);
