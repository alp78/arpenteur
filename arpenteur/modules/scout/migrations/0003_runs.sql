-- Stage execution, and the operator settings that decide what the stages do.
--
-- These sit in the scout module rather than the kernel for one reason: the
-- kernel must be able to run with no modules at all, and a `run` table only
-- means something once there is a stage to run. Every other module writes its
-- runs here, which is allowed because they all depend on the scout.
--
-- The line table exists because a run that reports only a final count is
-- unwatchable. Sixty thousand lines from one sweep is normal, so a watcher
-- asks for what it has not seen rather than re-reading the lot every poll.

CREATE TABLE IF NOT EXISTS intel.run (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage       TEXT NOT NULL,
    args_json   JSONB,
    started_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    stats_json  JSONB,
    error       TEXT,
    -- console | cli. A run started from the browser is one a person is
    -- watching, and the console settles orphans on startup: only its own.
    started_by  TEXT NOT NULL DEFAULT 'cli'
);

CREATE INDEX IF NOT EXISTS run_stage_idx ON intel.run (stage, started_at DESC);
CREATE INDEX IF NOT EXISTS run_open_idx ON intel.run (id) WHERE finished_at IS NULL;

CREATE TABLE IF NOT EXISTS intel.run_line (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES intel.run (id) ON DELETE CASCADE,
    -- Monotonic within a run. The watcher carries the sequence it has reached
    -- and asks for what is after it.
    seq    INTEGER NOT NULL,
    at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    text   TEXT NOT NULL,
    UNIQUE (run_id, seq)
);

-- What an operator changed, applied over arpenteur.toml at load.
--
-- The file keeps its comments and its defaults and stays the reference for
-- anyone reading the repository; a row here is this deployment's decision. The
-- alternative, rewriting the TOML from a web form, would destroy sixty lines
-- of explanation that are the reason the file is readable.
CREATE TABLE IF NOT EXISTS intel.setting (
    key        TEXT PRIMARY KEY,
    value_json JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Widening the territory changes what every later stage will spend money
    -- on, and that is a question asked after the bill rather than before it.
    updated_by TEXT
);
