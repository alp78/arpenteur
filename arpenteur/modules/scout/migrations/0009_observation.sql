-- Evidence that accumulates instead of being overwritten.
--
-- `intel.site` holds one row per company: the last research run's summary, its
-- signals, its judgement. Running enrich again replaces it. That is fine while
-- there is one source and it is always right, and wrong the moment there are
-- two, which there already are: the register says one thing about a company's
-- purpose, the website says another, and a SHAB notice a third. Today the last
-- writer wins and the disagreement is destroyed.
--
-- So an observation is a claim, by someone, at a time, from a document. Two
-- sources may contradict each other and both rows survive; what reads them
-- decides, and can say why. Nothing here deletes: an observation that turned
-- out to be wrong is superseded, which keeps the fact that it was once
-- believed and stops a re-run resurrecting it.
--
-- This does not replace `intel.site` yet and is not meant to in one step. The
-- research stage keeps writing its summary there while the observations
-- accumulate beside it; a reader that wants the disagreement asks here, and
-- one that wants the current best answer goes on asking there. Replacing a
-- working table in the same commit that introduces its successor is how a
-- migration becomes a rewrite.

-- Where a claim came from, kept once and pointed at many times.
CREATE TABLE IF NOT EXISTS intel.source_document (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id   BIGINT REFERENCES core.company (id) ON DELETE CASCADE,
    -- register | site | publication | note | document | mail | manual
    kind         TEXT NOT NULL,
    url          TEXT,
    title        TEXT,
    -- The bytes as fetched, by digest. Not the bytes themselves: a hundred
    -- thousand cached pages belong on a disk, and the cache already holds
    -- them. What this pins down is which version of a page a claim was read
    -- from, so "the site said so" can be checked rather than trusted.
    content_sha256 TEXT,
    -- What licence or permission the content came under. Zefix grants access
    -- on condition the origin is stated; a page fetched from a company's own
    -- site is quotable in a way a paid database is not. A claim whose source
    -- cannot be quoted is still worth holding and must not be repeated to a
    -- client, and that difference has to survive in the data.
    licence      TEXT,
    fetched_at   TIMESTAMPTZ,
    method       TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, kind, url, content_sha256)
);

CREATE INDEX IF NOT EXISTS source_document_company_idx
    ON intel.source_document (company_id, kind);

-- One claim about one company.
CREATE TABLE IF NOT EXISTS intel.observation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id   BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    -- A dotted path, so a reader can ask for a family: `site.signal`,
    -- `staff.count`, `system.named`, `need.stated`. Deliberately open rather
    -- than an enum: the attributes worth recording differ per campaign, and a
    -- constrained list would be edited by whoever hit it first.
    attribute    TEXT NOT NULL,
    value        TEXT,
    -- The same claim as a number where it is one, so "more than 50 staff" is a
    -- query rather than a string comparison.
    value_num    NUMERIC,
    -- 0 to 1. What the observer thought, not what a reader should think: a
    -- reader weighs this against the source and the parser version.
    confidence   NUMERIC(4, 3),
    source_document_id BIGINT REFERENCES intel.source_document (id) ON DELETE SET NULL,
    -- Which code produced it. A parser fixed in August makes every claim it
    -- made in July suspect, and this is what makes those findable instead of
    -- being rediscovered one wrong answer at a time.
    parser_version TEXT,
    method       TEXT,
    observed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Set when a later observation replaces this one. Never deleted: that it
    -- was once believed is itself a fact, and a deleted row is one a re-run
    -- will cheerfully write again.
    superseded_at TIMESTAMPTZ,
    superseded_by BIGINT REFERENCES intel.observation (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS observation_company_idx
    ON intel.observation (company_id, attribute);
CREATE INDEX IF NOT EXISTS observation_live_idx
    ON intel.observation (company_id, attribute) WHERE superseded_at IS NULL;
