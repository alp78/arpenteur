-- A score with its parts, its weights and its evidence.
--
-- `intel.fit.score` is one integer from one model call. It ranks a list, which
-- is what it was for, and it cannot answer the question anybody actually asks
-- of a ranked list: why is this one above that one. "78, because the reasoning
-- says so" is not an answer that survives being disagreed with.
--
-- Worse, one number conflates things that move independently. A company can be
-- an excellent fit that nobody can reach, or a mediocre fit whose chairman
-- sits on a board with an existing client, or exactly right and two years too
-- early. Averaged into a single figure those are all 60, and the three of them
-- want completely different actions.
--
-- So six components, each scored 0 to 100 on its own, each carrying the
-- evidence it was scored on, combined by a weight set that is versioned
-- because re-weighting a campaign must not rewrite what last month's ranking
-- was.
--
-- Two of the six are computed rather than judged. Reachability and
-- relationship are facts this database already holds: how many usable contacts
-- there are, and whether anybody on the board sits with anybody already being
-- worked. Asking a model to guess at those was always wrong, because it cannot
-- see them and will produce a number anyway.
--
-- `intel.fit` stays, written as a projection of the newest run, so every
-- reader that ranks by score goes on working. It is a view of this table now
-- rather than the record itself.

-- A named, versioned set of weights.
CREATE TABLE IF NOT EXISTS intel.weight_set (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    version    INTEGER NOT NULL DEFAULT 1,
    -- What the campaign was trying to find when these weights were chosen.
    note       TEXT,
    active     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (name, version)
);

-- Only one set is in force. A partial unique index rather than a flag nobody
-- enforces: two active sets means two rankings and no way to say which one a
-- list on screen came from.
CREATE UNIQUE INDEX IF NOT EXISTS weight_set_active_idx
    ON intel.weight_set ((active)) WHERE active;

CREATE TABLE IF NOT EXISTS intel.weight (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weight_set_id BIGINT NOT NULL REFERENCES intel.weight_set (id) ON DELETE CASCADE,
    component     TEXT NOT NULL,
    weight        NUMERIC(5, 3) NOT NULL,
    UNIQUE (weight_set_id, component)
);

-- One scoring of one company, at a moment, against a brief and a weight set.
CREATE TABLE IF NOT EXISTS intel.score_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    weight_set_id BIGINT REFERENCES intel.weight_set (id) ON DELETE SET NULL,
    total         NUMERIC(6, 2),
    band          TEXT,
    -- model | manual. A person's score is a run like any other, so the
    -- history reads as one sequence rather than as a table plus an exception.
    source        TEXT NOT NULL DEFAULT 'model',
    model         TEXT,
    -- The same two digests `intel.fit` carries, for the same reason: rewriting
    -- the brief invalidates exactly the scores taken against the old one.
    brief_hash    TEXT,
    site_hash     TEXT,
    reasoning     TEXT,
    advice        TEXT,
    author        TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS score_run_company_idx
    ON intel.score_run (company_id, created_at DESC);
CREATE INDEX IF NOT EXISTS score_run_total_idx ON intel.score_run (total DESC);

CREATE TABLE IF NOT EXISTS intel.score_component (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score_run_id BIGINT NOT NULL REFERENCES intel.score_run (id) ON DELETE CASCADE,
    component    TEXT NOT NULL,
    -- 0 to 100 on its own scale, before weighting.
    score        NUMERIC(6, 2),
    weight       NUMERIC(5, 3),
    -- model | computed. Which of the two produced this component, so a reader
    -- knows whether they are looking at a judgement or at a count.
    origin       TEXT NOT NULL DEFAULT 'model',
    reasoning    TEXT,
    UNIQUE (score_run_id, component)
);

-- What a component was scored on. One row per thing that argued either way.
CREATE TABLE IF NOT EXISTS intel.score_evidence (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score_component_id BIGINT NOT NULL
                       REFERENCES intel.score_component (id) ON DELETE CASCADE,
    -- for | against. A high component with a serious reservation is a real
    -- answer and has to be able to say so.
    direction          TEXT NOT NULL DEFAULT 'for',
    statement          TEXT NOT NULL,
    -- Where it came from, when it came from anything. Null for a judgement the
    -- model made from the whole file rather than from one document, which is
    -- honest and is why this is nullable rather than required.
    observation_id     BIGINT REFERENCES intel.observation (id) ON DELETE SET NULL,
    source_document_id BIGINT REFERENCES intel.source_document (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS score_evidence_component_idx
    ON intel.score_evidence (score_component_id);

-- What the ranking said at the moment somebody was picked out of it.
--
-- Outcomes are only ever observed for companies that were approached, and they
-- were approached because they scored well. Anything later learned from those
-- outcomes is therefore learned from the system's own past choices: the model
-- concludes that a high score predicts a win, partly because nothing with a
-- low score was ever tried. That bias cannot be corrected after the fact
-- because the scores themselves move.
--
-- So the propensity is written down at selection time. `selection_p` is this
-- company's percentile among everything scored at that instant, which is a
-- proxy for the probability of being selected under a top-of-the-list policy,
-- and it is enough to weight an analysis by its inverse later. It is not a
-- calibrated probability and must not be read as one.
ALTER TABLE intel.prospect ADD COLUMN IF NOT EXISTS selection_p NUMERIC(5, 4);
ALTER TABLE intel.prospect ADD COLUMN IF NOT EXISTS selection_score NUMERIC(6, 2);
ALTER TABLE intel.prospect ADD COLUMN IF NOT EXISTS selection_band TEXT;
ALTER TABLE intel.prospect ADD COLUMN IF NOT EXISTS selected_at TIMESTAMPTZ;
