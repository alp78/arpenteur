-- Money: what is on offer, what was quoted, what was billed, what it took.
--
-- This is the module that must be removable without breaking anything, so it
-- is the one where the direction of every foreign key matters most. Everything
-- here points at `crm` and `core`; nothing there points back. Dropping this
-- schema leaves the survey, the clients, the dossiers and the timelines
-- exactly as they were, and Postgres would refuse the drop if that were not
-- true.
--
-- Four decisions.
--
-- A SERVICE IS A ROW, NOT PROSE. The rate card used to live as a paragraph in
-- a settings field, which meant the advise stage priced from text and nothing
-- could ask "how often have I proposed a diagnostic, at what price, and how
-- many converted". A catalogue makes that a query.
--
-- THE RATE CARD IS VERSIONED. Prices change, and a quote sent in March was
-- computed against March's card. Keeping only today's card makes every past
-- quote unexplainable.
--
-- A SENT QUOTE IS NEVER EDITED. A revision is a new version with its own
-- lines, its own total and its own PDF. The alternative silently rewrites what
-- a client is holding in their inbox.
--
-- A QUOTE BELONGS TO A PROJECT, NOT TO A COMPANY. One client can have several
-- pieces of work in flight and a quote is always for one of them. Hanging it
-- off the company is how a system ends up unable to say what was won.

CREATE SCHEMA IF NOT EXISTS commercial;

-- What is on offer, in the operator's own words.
CREATE TABLE IF NOT EXISTS commercial.service (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          TEXT NOT NULL UNIQUE,
    name          TEXT NOT NULL,
    -- The deliverable, in one paragraph. Read into the advise prompt verbatim,
    -- so it is written for a reader rather than as a label.
    what          TEXT,
    -- What must be true or known before it can start. Most implementation work
    -- is prerequisite on a diagnostic, and saying so stops it being quoted as
    -- though it could begin on Monday.
    prerequisite  TEXT,
    -- fixed | day | month | hour. How the price is expressed, which decides
    -- how a quote line multiplies out.
    unit          TEXT NOT NULL DEFAULT 'fixed',
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order    INTEGER NOT NULL DEFAULT 100,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ
);

-- A dated set of prices. Only one is current; the rest are why an old quote
-- says what it says.
CREATE TABLE IF NOT EXISTS commercial.rate_card (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    valid_from DATE NOT NULL,
    valid_to   DATE,
    currency   TEXT NOT NULL DEFAULT 'CHF',
    note       TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS commercial.rate_card_line (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_card_id BIGINT NOT NULL REFERENCES commercial.rate_card (id) ON DELETE CASCADE,
    service_id   BIGINT NOT NULL REFERENCES commercial.service (id) ON DELETE CASCADE,
    -- A range, because that is how the work is actually quoted, and what moves
    -- a price inside it belongs in `basis` rather than in the operator's head.
    low          NUMERIC(12, 2),
    high         NUMERIC(12, 2),
    basis        TEXT,
    UNIQUE (rate_card_id, service_id)
);

-- A proposal. Never edited once sent: a revision is a new version.
CREATE TABLE IF NOT EXISTS commercial.quote (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id  BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    project_id BIGINT REFERENCES crm.project (id) ON DELETE SET NULL,
    -- BOIS-GENTIL-Q01. Quoted on the phone, so it is readable rather than a
    -- surrogate integer.
    code       TEXT NOT NULL UNIQUE,
    -- draft | sent | accepted | declined | expired | withdrawn
    status     TEXT NOT NULL DEFAULT 'draft',
    currency   TEXT NOT NULL DEFAULT 'CHF',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Set when the client says yes, in writing. The one date an invoice may be
    -- raised against.
    accepted_at TIMESTAMPTZ,
    -- Why not, when not. A pipeline that records only wins cannot be learned
    -- from.
    lost_reason TEXT
);

CREATE INDEX IF NOT EXISTS quote_client_idx ON commercial.quote (client_id, created_at DESC);
CREATE INDEX IF NOT EXISTS quote_status_idx ON commercial.quote (status);

CREATE TABLE IF NOT EXISTS commercial.quote_version (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id     BIGINT NOT NULL REFERENCES commercial.quote (id) ON DELETE CASCADE,
    version      INTEGER NOT NULL,
    rate_card_id BIGINT REFERENCES commercial.rate_card (id) ON DELETE SET NULL,
    intro        TEXT,
    terms        TEXT,
    valid_until  DATE,
    -- Totals stored, not computed on read. A quote is a document that was sent
    -- at a moment; recomputing it later from lines that may have been edited
    -- would make the archive lie.
    net_total    NUMERIC(14, 2),
    vat_rate     NUMERIC(5, 3),
    vat_total    NUMERIC(14, 2),
    gross_total  NUMERIC(14, 2),
    -- The PDF as delivered, by content digest, in the same store as client
    -- attachments.
    pdf_sha256   TEXT,
    sent_at      TIMESTAMPTZ,
    sent_to      TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (quote_id, version)
);

CREATE TABLE IF NOT EXISTS commercial.quote_line (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_version_id BIGINT NOT NULL
                     REFERENCES commercial.quote_version (id) ON DELETE CASCADE,
    -- Nullable so a one-off line is possible, but the catalogue is the norm:
    -- a line with no service cannot be counted in "what converts".
    service_id       BIGINT REFERENCES commercial.service (id) ON DELETE SET NULL,
    position         INTEGER NOT NULL DEFAULT 1,
    -- Copied from the service at the time, not joined at read. The catalogue
    -- entry may be reworded next year; what the client received must not
    -- change with it.
    label            TEXT NOT NULL,
    detail           TEXT,
    unit             TEXT NOT NULL DEFAULT 'fixed',
    quantity         NUMERIC(10, 2) NOT NULL DEFAULT 1,
    unit_price       NUMERIC(12, 2) NOT NULL DEFAULT 0,
    amount           NUMERIC(14, 2) NOT NULL DEFAULT 0,
    -- Which rate card line it came from, so a price can be traced rather than
    -- defended from memory.
    basis            TEXT
);

CREATE INDEX IF NOT EXISTS quote_line_version_idx
    ON commercial.quote_line (quote_version_id, position);

-- What was billed. Swiss TVA, sequential numbering, QR-bill fields.
CREATE TABLE IF NOT EXISTS commercial.invoice (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    project_id  BIGINT REFERENCES crm.project (id) ON DELETE SET NULL,
    quote_id    BIGINT REFERENCES commercial.quote (id) ON DELETE SET NULL,
    -- Gapless and sequential, because the tax authority expects it. Allocated
    -- by a sequence rather than by counting rows, so a rolled-back transaction
    -- cannot hand the same number out twice.
    number      TEXT NOT NULL UNIQUE,
    -- draft | issued | paid | part_paid | overdue | credited | cancelled.
    -- An issued invoice is never edited: a correction is a credit note.
    status      TEXT NOT NULL DEFAULT 'draft',
    issued_on   DATE,
    due_on      DATE,
    currency    TEXT NOT NULL DEFAULT 'CHF',
    net_total   NUMERIC(14, 2) NOT NULL DEFAULT 0,
    vat_rate    NUMERIC(5, 3),
    vat_total   NUMERIC(14, 2) NOT NULL DEFAULT 0,
    gross_total NUMERIC(14, 2) NOT NULL DEFAULT 0,
    paid_total  NUMERIC(14, 2) NOT NULL DEFAULT 0,
    paid_on     DATE,
    -- The QR-IBAN and the structured creditor reference that go on the Swiss
    -- QR-bill. Stored per invoice because the reference encodes the invoice.
    qr_iban     TEXT,
    qr_reference TEXT,
    pdf_sha256  TEXT,
    note        TEXT,
    -- The credit note that reverses this one, if any.
    credits_id  BIGINT REFERENCES commercial.invoice (id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS invoice_client_idx ON commercial.invoice (client_id, issued_on DESC);
CREATE INDEX IF NOT EXISTS invoice_status_idx ON commercial.invoice (status);

CREATE SEQUENCE IF NOT EXISTS commercial.invoice_number_seq;

CREATE TABLE IF NOT EXISTS commercial.invoice_line (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES commercial.invoice (id) ON DELETE CASCADE,
    service_id BIGINT REFERENCES commercial.service (id) ON DELETE SET NULL,
    position   INTEGER NOT NULL DEFAULT 1,
    label      TEXT NOT NULL,
    detail     TEXT,
    unit       TEXT NOT NULL DEFAULT 'fixed',
    quantity   NUMERIC(10, 2) NOT NULL DEFAULT 1,
    unit_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    amount     NUMERIC(14, 2) NOT NULL DEFAULT 0,
    vat_rate   NUMERIC(5, 3)
);

CREATE INDEX IF NOT EXISTS invoice_line_invoice_idx
    ON commercial.invoice_line (invoice_id, position);

-- What the work took. Feeds day-rate and retainer lines, and answers the
-- question a fixed fee never does: whether it was worth it.
CREATE TABLE IF NOT EXISTS commercial.time_entry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   BIGINT NOT NULL REFERENCES crm.client (id) ON DELETE CASCADE,
    project_id  BIGINT REFERENCES crm.project (id) ON DELETE SET NULL,
    service_id  BIGINT REFERENCES commercial.service (id) ON DELETE SET NULL,
    occurred_on DATE NOT NULL,
    minutes     INTEGER NOT NULL,
    note        TEXT,
    -- Billable is a decision, not a property. Travel inside the surveyed
    -- cantons is not billed, and recording it as zero minutes would lose the
    -- fact that the time was spent.
    billable    BOOLEAN NOT NULL DEFAULT TRUE,
    -- Set once the minutes appear on an invoice line, so nothing is billed
    -- twice.
    invoice_line_id BIGINT REFERENCES commercial.invoice_line (id) ON DELETE SET NULL,
    author      TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS time_entry_client_idx
    ON commercial.time_entry (client_id, occurred_on DESC);
CREATE INDEX IF NOT EXISTS time_entry_unbilled_idx
    ON commercial.time_entry (project_id) WHERE invoice_line_id IS NULL;
