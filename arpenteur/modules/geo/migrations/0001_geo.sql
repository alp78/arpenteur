-- Where things are.
--
-- The register gives a postal address and no coordinates. Measured on
-- 12.08.2026: 3'690 of 184'939 companies carried an address at all, and none
-- carried a point. So a map is a data-acquisition problem before it is a
-- database one, and this schema is mostly a place to put what geocoding
-- returns, with the provenance to say where each point came from and when.
--
-- AN ESTABLISHMENT, NOT A COMPANY. A company is a legal entity and has no
-- location; its establishments do. Fondation Bois-Gentil is one entity across
-- seven sites, and a single marker for it would be wrong in six places.
--
-- THE POINT IS SEPARATE FROM THE ADDRESS. An address is what the register or
-- the client told us. A point is what a geocoder made of it, at a confidence,
-- on a date, and it can be wrong while the address is right. Keeping them in
-- one row would make a bad geocode indistinguishable from a bad address.

CREATE SCHEMA IF NOT EXISTS geo;

-- A postal address as given, normalised only as far as is safe.
CREATE TABLE IF NOT EXISTS geo.address (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    street       TEXT,
    house_number TEXT,
    po_box       TEXT,
    postal_code  TEXT,
    city         TEXT,
    canton       TEXT,
    country      TEXT NOT NULL DEFAULT 'CH',
    -- The single line handed to the geocoder, kept so a bad result can be
    -- reproduced exactly rather than guessed at.
    query        TEXT,
    source_url   TEXT,
    method       TEXT,
    fetched_at   TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (street, house_number, postal_code, city, country)
);

CREATE INDEX IF NOT EXISTS address_postal_idx ON geo.address (postal_code);

-- One place a company operates from.
CREATE TABLE IF NOT EXISTS geo.establishment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id  BIGINT NOT NULL REFERENCES core.company (id) ON DELETE CASCADE,
    address_id  BIGINT REFERENCES geo.address (id) ON DELETE SET NULL,
    -- What this site is called locally: "EMS Petit-Flon", "Résidence Vallon".
    name        TEXT,
    kind        TEXT,
    is_seat     BOOLEAN NOT NULL DEFAULT FALSE,
    -- geography rather than geometry: distances come out in metres without
    -- anyone choosing a projection, and "within 30 km of Lausanne" is the
    -- query this table exists for.
    point       geography(Point, 4326),
    -- How the point was obtained and how much to trust it. `precision` is the
    -- geocoder's own word for what it matched: an exact address, a street, or
    -- merely the town, and a marker placed on a town centre should not look
    -- like one placed on a door.
    geocoder    TEXT,
    precision   TEXT,
    confidence  REAL,
    geocoded_at TIMESTAMPTZ,
    source_url  TEXT,
    method      TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS establishment_company_idx ON geo.establishment (company_id);
CREATE INDEX IF NOT EXISTS establishment_point_idx ON geo.establishment USING gist (point);
-- What still needs geocoding, as a partial index, because that is the query
-- the stage runs and it will run it against a table where most rows are done.
CREATE INDEX IF NOT EXISTS establishment_ungeocoded_idx
    ON geo.establishment (company_id) WHERE point IS NULL;

-- A territory: a canton, a commune, a postal area, or one drawn by hand.
CREATE TABLE IF NOT EXISTS geo.region (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       TEXT NOT NULL,
    name       TEXT NOT NULL,
    -- canton | district | commune | postal | custom
    kind       TEXT NOT NULL,
    -- geometry rather than geography here: containment and rendering are what
    -- these are for, and a cantonal boundary is stored once and read often.
    shape      geometry(MultiPolygon, 4326),
    source_url TEXT,
    method     TEXT,
    fetched_at TIMESTAMPTZ,
    UNIQUE (kind, code)
);

CREATE INDEX IF NOT EXISTS region_shape_idx ON geo.region USING gist (shape);
